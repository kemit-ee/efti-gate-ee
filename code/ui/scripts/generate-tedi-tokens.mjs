import {readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {dirname, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const corePkgPath = require.resolve('@tedi-design-system/core/package.json')
const corePkg = JSON.parse(readFileSync(corePkgPath, 'utf8'))
const tokens = JSON.parse(readFileSync(resolve(dirname(corePkgPath), 'tokens.json'), 'utf8'))

const zIndex = {
  'z-index-sticky': '1020',
  'z-index-sidenav': '1030',
  'z-index-bottom-header': '1040',
  'z-index-header': '1050',
  'z-index-feedback': '1060',
  'z-index-fixed': '1070',
  'z-index-modal': '1080',
  'z-index-tooltip': '1090',
  'z-index-dropdown': '1100',
}

function declarations(entries) {
  return entries.map(([name, token]) => `  --${name}: ${token.value};`).join('\n')
}

const defaultTheme = tokens.themes.default
const base = Object.entries(defaultTheme.base)
const semantic = Object.entries(defaultTheme.semantic)
const dark = Object.entries(tokens.themes.dark?.semantic ?? {})
const zIndexEntries = Object.entries(zIndex).map(([name, value]) => [name, {value}])

const output = [
  `/* Generated by scripts/generate-tedi-tokens.mjs from @tedi-design-system/core@${corePkg.version} tokens.json. Do not edit. */`,
  ':root {',
  declarations(base),
  '',
  declarations(semantic),
  '',
  declarations(zIndexEntries),
  '}',
  '',
  '.dark {',
  declarations(dark),
  '}',
  '',
].join('\n')

writeFileSync(resolve(root, 'src/tedi-tokens.css'), output)
console.log(`Wrote src/tedi-tokens.css (${base.length} base + ${semantic.length} semantic + ${dark.length} dark tokens, core ${corePkg.version})`)
