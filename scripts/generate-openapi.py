#!/usr/bin/env python3
"""Generate docs/specs/openapi.generated.yaml from the routes Ruuter really serves (#362).

Ruuter builds an OpenAPI document from the DSL tree at boot (`GET /_/openapi.json`, admin-gated by
RUUTER_ADMIN_ENABLED, which the gate never sets on its own listener). This script starts the runtime image with the
DSL tree, ruuter.yaml and constants.ini mounted read-only and the admin gate on, on a loopback port of its own, fetches the
document, removes what is engine noise and writes a deterministic YAML file. Nothing is hand-edited in the output.

Run without arguments to regenerate, with --check to fail when the file is stale (CI). Needs docker and PyYAML.
"""
import argparse
import json
import pathlib
import socket
import subprocess
import sys
import time
import urllib.request

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "specs" / "openapi.generated.yaml"
IMAGE = "turnerrainer/ruuter:0.12.1-rc"

HEADER = """# Generated by scripts/generate-openapi.py from the Ruuter DSL tree (DSL/Ruuter). Do not edit.
# The routes the gate's Ruuter serves, with their declared inputs. Curated prose, the EU reference API and the error
# catalogue are elsewhere: docs/specs/openapi.yaml (reference contract), docs/specs/errors.json.
"""

DESCRIPTION = (
    "The HTTP routes served by the gate's Ruuter (`DSL/Ruuter`), generated from the DSL declarations "
    "(`declaration.allowlist`, `returns`). It lists what runs: paths, methods, declared query/body/header inputs and "
    "the status codes the engine can return. It does not describe the response bodies in detail, the guards "
    "(see `docs/specs/permissions-matrix.md`) or the error bodies (`docs/specs/errors.json`, RFC 7807). The X-Road provider "
    "surface is served by a separate Ruuter and described by `GET /xroad/provide/openapi`."
)


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def fetch():
    port = free_port()
    name = f"efti-openapi-gen-{port}"
    run = ["docker", "run", "-d", "--rm", "--name", name, "-p", f"127.0.0.1:{port}:8086", "-e", "RUUTER_ADMIN_ENABLED=true",
           "-v", f"{ROOT / 'ruuter.yaml'}:/app/ruuter.yaml:ro", "-v", f"{ROOT / 'DSL' / 'Ruuter'}:/app/DSL:ro",
           "-v", f"{ROOT / 'constants.ini'}:/app/constants.ini:ro", IMAGE]
    subprocess.run(run, check=True, stdout=subprocess.DEVNULL)
    try:
        for _ in range(60):
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{port}/_/openapi.json", timeout=5) as r:
                    return json.load(r)
            except OSError:
                time.sleep(1)
        logs = subprocess.run(["docker", "logs", name], capture_output=True, text=True).stdout[-1500:]
        sys.exit(f"Ruuter did not serve /_/openapi.json within 60 s:\n{logs}")
    finally:
        subprocess.run(["docker", "rm", "-f", name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def clean(doc):
    doc["info"] = {"title": "eFTI Gate (EE) - routes served by Ruuter (generated)", "version": "generated", "description": DESCRIPTION}
    doc.pop("servers", None)
    for methods in doc.get("paths", {}).values():
        for op in methods.values():
            if isinstance(op, dict) and "parameters" in op:
                # the engine lists the route's own path-parameter map as a query parameter
                op["parameters"] = [p for p in op["parameters"] if p.get("name") != "pathParams"]
                if not op["parameters"]:
                    del op["parameters"]
    return doc


def render():
    return HEADER + yaml.safe_dump(clean(fetch()), sort_keys=True, allow_unicode=True, width=120)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs from what Ruuter serves now")
    text = render()
    if parser.parse_args().check:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit(f"{TARGET.relative_to(ROOT)} is stale: run python3 scripts/generate-openapi.py and commit the result")
        print("openapi.generated.yaml is current")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
