#!/usr/bin/env python3
"""Write the canned datasets into both DSL routes that serve them, so the public X-Road developer
mock and the live gate (via its mock platform) answer the same UIL with the same dataset.

  DSL/Ruuter-xroad-mock/developer/POST/v1/dataset.yml  {uil, subsets, xml, consignment}
  DSL/Ruuter/mock-platform/GET/v1/dataset.yml          the platform XML the live gate maps itself
  docs/developer/fti010-field-catalogue.md             every field of the full-field dataset ...0002

The XML comes from scripts/generate-rich-mock-dataset.py; the mock's `xml` and `consignment` are
precomputed the way xml-mapper's /api/v1/dataset/response-to-json derives them on the live gate. Run with --check to only
verify that all three files are current (exit 1 otherwise).
"""
from pathlib import Path
import importlib.util
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("fixture", ROOT / "scripts/generate-rich-mock-dataset.py")
fixture = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fixture)

MOCK = ROOT / "DSL/Ruuter-xroad-mock/developer/POST/v1/dataset.yml"
PLATFORM = ROOT / "DSL/Ruuter/mock-platform/GET/v1/dataset.yml"
CATALOGUE = ROOT / "docs/developer/fti010-field-catalogue.md"
HEADER = "# Generated by scripts/sync-mock-datasets.py from scripts/generate-rich-mock-dataset.py. Do not edit.\n"


def step_name(dataset_id):
    return "respond_" + dataset_id[-4:]


def block(text, indent, keep=""):
    pad = " " * indent
    return "|" + keep + "\n" + "".join(pad + line + "\n" if line else "\n" for line in text.rstrip("\n").split("\n"))


def mapping(data, indent):
    dumped = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, default_flow_style=False, width=1000)
    return "".join(" " * indent + line + "\n" for line in dumped.rstrip("\n").split("\n"))


def mock_route():
    datasets = [(dataset_id, make()) for dataset_id, make in fixture.DATASETS.items()]
    out = [HEADER, """declaration:
  description: "Developer mock - imitates POST /xroad/v1/dataset. Returns the same canned FTI010
    dataset the live gate's mock platform serves, plus the `consignment` object xml-mapper derives
    from it. EU-EE/mock datasets ...0002 (full-field fixture) and ...0011-...0013 (MOCK-PLATE-3
    shipments) have their own XML; every other UIL gets the minimal MOCK-PLATE-1 fixture.
    Member code 70000000 is entitled to nothing -> 403 FORBIDDEN_SUBSET, so the error path is
    exercisable."
  internal: false
  returns:
    - field: uil
      type: object
    - field: subsets
      type: array
    - field: xml
      type: string
    - field: consignment
      type: object
  additive: true
  allowlist:
    body:
      - field: subsets
        type: array
      - field: uil
        type: object

check_subsets_present:
  switch:
    - condition: ${incoming.body == null || incoming.body.subsets == null || incoming.body.subsets.length == 0}
      next: missing_subset
  next: check_subset_permission

check_subset_permission:
  switch:
    - condition: ${memberCode == '70000000'}
      next: forbidden_subset
  next: select_dataset

select_dataset:
  switch:
"""]
    for dataset_id, _ in datasets:
        out.append(f"    - condition: ${{incoming.body?.uil?.gateId == 'EU-EE' && incoming.body.uil.platformId == 'mock' "
                   f"&& incoming.body.uil.datasetId == '{dataset_id}'}}\n      next: {step_name(dataset_id)}\n")
    out.append("  next: respond\n")
    for name, xml in [(step_name(dataset_id), xml) for dataset_id, xml in datasets] + [("respond", fixture.SIMPLE)]:
        out.append(f"\n{name}:\n  return:\n    uil: ${{incoming.body.uil}}\n    subsets: ${{incoming.body.subsets}}\n"
                   f"    xml: {block(fixture.served_xml(xml), 6, keep='-')}    consignment:\n{mapping(fixture.consignment(xml), 6)}"
                   "  wrapper: false\n  status: 200\n  next: end\n")
    out.append("""
missing_subset:
  return:
    type: "https://api.efti.ee/errors/missing-subset"
    code: "MISSING_SUBSET"
    title: "Missing Subset Parameter"
    status: 400
    detail: "At least one subset must be requested."
  wrapper: false
  status: 400
  next: end

forbidden_subset:
  return:
    type: "https://api.efti.ee/errors/forbidden-subset"
    code: "FORBIDDEN_SUBSET"
    title: "Subset Access Denied"
    status: 403
    detail: "The requesting authority is not permitted to access one or more of the requested eFTI subsets."
    authorityId: "auth-mock"
    deniedSubsets: ${incoming.body.subsets}
    permittedSubsets: []
  wrapper: false
  status: 403
  next: end
""")
    return "".join(out)


def platform_route():
    out = [HEADER, """declaration:
  description: "Mock platform endpoint returning a sample FTI010 dataset for GET /v1/dataset/:datasetId.
    Serves the same XML as the public developer mock for the same datasetId; any other id gets the
    minimal MOCK-PLATE-1 fixture. The subsets query parameter is not applied."
  internal: false
  returns: []
  additive: true
  allowlist:
    params:
      - field: pathParams

check_api_key:
  switch:
    - condition: ${incoming.headers['x-api-key'] != 'mock-secret-key'}
      next: unauthorized

select_dataset:
  switch:
"""]
    for dataset_id in fixture.DATASETS:
        out.append(f"    - condition: ${{incoming.params.pathParams?.[0] == '{dataset_id}'}}\n      next: {step_name(dataset_id)}\n")
    out.append("  next: respond\n")
    for name, xml in [(step_name(d), make()) for d, make in fixture.DATASETS.items()] + [("respond", fixture.SIMPLE)]:
        out.append(f"\n{name}:\n  return: {block(xml, 4)}  headers:\n    Content-Type: \"text/xml\"\n"
                   "  wrapper: false\n  status: 200\n  next: end\n")
    out.append("""
unauthorized:
  return:
    error: "Unauthorized"
  status: 401
  wrapper: false
""")
    return "".join(out)


if __name__ == "__main__":
    stale = []
    for path, text in ((MOCK, mock_route()), (PLATFORM, platform_route()), (CATALOGUE, fixture.catalogue())):
        if not path.exists() or path.read_text() != text:
            stale.append(path.relative_to(ROOT))
            if "--check" not in sys.argv:
                path.write_text(text)
    if stale and "--check" in sys.argv:
        sys.exit("stale, run scripts/sync-mock-datasets.py: " + ", ".join(map(str, stale)))
    print("updated: " + ", ".join(map(str, stale)) if stale else "up to date")
