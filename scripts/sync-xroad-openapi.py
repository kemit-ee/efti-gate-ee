#!/usr/bin/env python3
"""Generate the ruuter-xroad OpenAPI route from docs/developer/x_road_openapi.yaml.

The consumer-facing contract (docs/developer/x_road_openapi.yaml, the one hand-edited source) is rewritten to
the provider-side paths ruuter-xroad really serves (/echo/v1 -> /xroad/v1/echo), given the unauthenticated
health and description routes, and embedded as a canned response in
DSL/Ruuter-xroad/xroad/GET/provide/openapi.yml (GET /xroad/provide/openapi). Ruuter has no static file
serving, so the document is baked into the DSL the way the developer mock's datasets are.

Run without arguments to regenerate, with --check to fail when the route is stale (CI).
"""
import copy
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "developer" / "x_road_openapi.yaml"
TARGET = ROOT / "DSL" / "Ruuter-xroad" / "xroad" / "GET" / "provide" / "openapi.yml"

HEADER = """# Generated by scripts/sync-xroad-openapi.py from docs/developer/x_road_openapi.yaml. Do not edit.
declaration:
  description: "Provider-side OpenAPI description of the X-Road surface served by ruuter-xroad. Public
    on purpose (xroad/GET/provide/.guard.yml overrides the project guard): the Security Server fetches
    the service description without an X-Road-Client header. No inputs."
  internal: false
  returns:
    - field: openapi
      type: string
    - field: info
      type: object
    - field: paths
      type: object

respond:
  return:
"""
FOOTER = """  status: 200
  wrapper: false
  next: end
"""

HEALTH = {
    "get": {
        "tags": ["Health"],
        "operationId": "xroadReadiness",
        "summary": "Readiness probe",
        "description": "Returns 200 only if the database is reachable, 503 otherwise. Public, no X-Road headers.",
        "security": [],
        "responses": {
            "200": {"description": "Ready", "content": {"text/plain": {"schema": {"type": "string"}, "example": "OK"}}},
            "503": {"description": "Database unavailable", "content": {"text/plain": {"schema": {"type": "string"}}}},
        },
    }
}
DESCRIPTION_ROUTE = {
    "get": {
        "tags": ["Health"],
        "operationId": "xroadOpenapi",
        "summary": "This OpenAPI description",
        "description": "Public, no X-Road headers: the Security Server reads the service description from here.",
        "security": [],
        "responses": {
            "200": {"description": "The OpenAPI 3.0 document", "content": {"application/json": {"schema": {"type": "object"}}}}
        },
    }
}


def build():
    doc = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    out = copy.deepcopy(doc)
    out["servers"] = [{
        "url": "/",
        "description": "Provider side: the gate's Security Server forwards each X-Road service call to this ruuter-xroad "
                       "(never publicly routable, ADR-006).",
    }]
    paths = {}
    for key, value in doc["paths"].items():
        m = re.fullmatch(r"/([a-z-]+)/v1", key)
        if not m:
            raise SystemExit(f"unexpected path {key!r} in {SOURCE.name}")
        paths[f"/xroad/v1/{m.group(1)}"] = value
    paths["/xroad/health/ready"] = HEALTH
    paths["/xroad/provide/openapi"] = DESCRIPTION_ROUTE
    out["paths"] = paths
    out["tags"] = list(doc.get("tags", [])) + [{"name": "Health", "description": "Probes and the service description; no authentication"}]
    return out


def check_literals(node, where="$"):
    if isinstance(node, dict):
        for k, v in node.items():
            check_literals(k, where)
            check_literals(v, f"{where}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            check_literals(v, f"{where}[{i}]")
    elif isinstance(node, str) and ("${" in node or "[#" in node):
        raise SystemExit(f"{where}: Ruuter would evaluate this string ('${{' or '[#'): {node[:60]!r}")


def ascii_dashes(node):
    # dsl-lint warns on U+2014 in DSL files; the source document keeps its typography.
    if isinstance(node, dict):
        return {ascii_dashes(k): ascii_dashes(v) for k, v in node.items()}
    if isinstance(node, list):
        return [ascii_dashes(v) for v in node]
    if isinstance(node, str):
        return node.replace("—", "-")
    return node


def render():
    spec = ascii_dashes(build())
    check_literals(spec)
    body = yaml.safe_dump(spec, allow_unicode=True, sort_keys=False, default_flow_style=False, width=1000)
    indented = "".join(("    " + line if line.strip() else line) for line in body.splitlines(keepends=True))
    return HEADER + indented + FOOTER


def main():
    content = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"STALE {TARGET.relative_to(ROOT)}: run python3 scripts/sync-xroad-openapi.py", file=sys.stderr)
            return 1
        print("OK    xroad OpenAPI route is current")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
